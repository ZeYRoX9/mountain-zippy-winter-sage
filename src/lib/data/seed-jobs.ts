function job(partial: SeedJob): SeedJob {
  return {
    ...partial,
    checks: partial.checks.length ? partial.checks : completenessChecks(partial.qualityFlags),
    verificationSummary: partial.verificationSummary || summary,
    lastVerifiedOn: partial.lastVerifiedOn || REVIEWED_ON,
    howToApply:
      partial.howToApply ||
      "Apply on HiredFrex using the form on this page. Do not pay anyone to apply. If someone claiming to represent this employer asks for money, documents via personal chat apps, or an off-platform processing fee, report the listing.",
  };
}

